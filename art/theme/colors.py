#!/usr/bin/env python3
"""
The app's own colour schemes (ui/theme/Palette.kt), light and dark, from the app icon's colours –
what Android before 12 shows; from 12 on, the app takes its colours from the wallpaper.

Material 3 builds a scheme from tonal palettes: one hue at a set colourfulness (chroma), in tones
from 0 (black) to 100 (white), each role taking a fixed tone. Material's own tool works in its HCT
colour space; this one uses CIE LCh, whose lightness is the same as HCT's tone, which is what makes
the contrasts right – the hues come out a little differently, which does not matter here.

    python3 art/theme/colors.py
"""
import math
import os

# sRGB <-> CIE LCh (D65).
def srgb_to_lin(c): c/=255; return c/12.92 if c<=0.04045 else ((c+0.055)/1.055)**2.4
def lin_to_srgb(c): return 12.92*c if c<=0.0031308 else 1.055*c**(1/2.4)-0.055
Xn,Yn,Zn=0.95047,1.0,1.08883
def f(t): return t**(1/3) if t>216/24389 else (24389/27*t+16)/116
def finv(t): return t**3 if t**3>216/24389 else (116*t-16)/(24389/27)
def hex2lch(h):
    r,g,b=[srgb_to_lin(int(h[i:i+2],16)) for i in (1,3,5)]
    X=0.4124*r+0.3576*g+0.1805*b; Y=0.2126*r+0.7152*g+0.0722*b; Z=0.0193*r+0.1192*g+0.9505*b
    fx,fy,fz=f(X/Xn),f(Y/Yn),f(Z/Zn); L=116*fy-16; a=500*(fx-fy); bb=200*(fy-fz)
    return L, math.hypot(a,bb), math.degrees(math.atan2(bb,a))%360
def lch2rgb(L,C,H):
    a=C*math.cos(math.radians(H)); b=C*math.sin(math.radians(H)); fy=(L+16)/116; fx=fy+a/500; fz=fy-b/200
    X,Y,Z=Xn*finv(fx),Yn*finv(fy),Zn*finv(fz)
    r=3.2406*X-1.5372*Y-0.4986*Z; g=-0.9689*X+1.8758*Y+0.0415*Z; bl=0.0557*X-0.2040*Y+1.0570*Z
    return r,g,bl
def in_gamut(rgb): return all(-1e-6 <= v <= 1 + 1e-6 for v in rgb)
def tone(H, C, T):
    """The colour of hue H at tone T, as colourful as C allows – less where sRGB cannot show C (0xAARRGGBB)."""
    c = C
    if not in_gamut(lch2rgb(T, C, H)):
        lo, hi = 0.0, C
        for _ in range(30):
            mid = (lo + hi) / 2
            lo, hi = (mid, hi) if in_gamut(lch2rgb(T, mid, H)) else (lo, mid)
        c = lo
    return '0xFF' + ''.join('%02X' % round(max(0, min(1, lin_to_srgb(max(0, v)))) * 255) for v in lch2rgb(T, c, H))

# The app icon's colours: the blue behind the helmet and its yellow dome.
BLUE, YELLOW = '#005EA2', '#FEE400'
_, _, hb = hex2lch(BLUE)
_, _, hy = hex2lch(YELLOW)
# Tonal palettes: the primary is the icon's blue, strong; the secondary a quiet blue grey; the tertiary
# the helmet's brass; the neutrals greys with a trace of the blue.
P = lambda t: tone(hb, 60, t)
S = lambda t: tone(hb, 16, t)
T = lambda t: tone(hy, 42, t)
N = lambda t: tone(hb, 4, t)
NV = lambda t: tone(hb, 9, t)
# The tones Material 3 gives each role.
LIGHT = dict(primary=P(40), onPrimary=P(100), primaryContainer=P(90), onPrimaryContainer=P(30), inversePrimary=P(80),
    secondary=S(40), onSecondary=S(100), secondaryContainer=S(90), onSecondaryContainer=S(30),
    tertiary=T(40), onTertiary=T(100), tertiaryContainer=T(90), onTertiaryContainer=T(30),
    background=N(98), onBackground=N(10), surface=N(98), onSurface=N(10), surfaceVariant=NV(90), onSurfaceVariant=NV(30),
    surfaceTint=P(40), inverseSurface=N(20), inverseOnSurface=N(95), outline=NV(50), outlineVariant=NV(80),
    surfaceBright=N(98), surfaceDim=N(87), surfaceContainerLowest=N(100), surfaceContainerLow=N(96),
    surfaceContainer=N(94), surfaceContainerHigh=N(92), surfaceContainerHighest=N(90))
DARK = dict(primary=P(80), onPrimary=P(20), primaryContainer=P(30), onPrimaryContainer=P(90), inversePrimary=P(40),
    secondary=S(80), onSecondary=S(20), secondaryContainer=S(30), onSecondaryContainer=S(90),
    tertiary=T(80), onTertiary=T(20), tertiaryContainer=T(30), onTertiaryContainer=T(90),
    background=N(6), onBackground=N(90), surface=N(6), onSurface=N(90), surfaceVariant=NV(30), onSurfaceVariant=NV(80),
    surfaceTint=P(80), inverseSurface=N(90), inverseOnSurface=N(20), outline=NV(60), outlineVariant=NV(30),
    surfaceBright=N(24), surfaceDim=N(6), surfaceContainerLowest=N(4), surfaceContainerLow=N(10),
    surfaceContainer=N(12), surfaceContainerHigh=N(17), surfaceContainerHighest=N(22))

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
    '../../app/src/main/java/org/rustygnome/pickelhaube/ui/theme/Palette.kt')
with open(OUT, 'w') as out:
    out.write('package org.rustygnome.pickelhaube.ui.theme\n\n'
        'import androidx.compose.material3.darkColorScheme\n'
        'import androidx.compose.material3.lightColorScheme\n'
        'import androidx.compose.ui.graphics.Color\n\n'
        '// Generated by art/theme/colors.py from the app icon\'s colours – change that and run it, not this.\n')
    for name, roles, doc in (('PickelhaubeLight', LIGHT, 'light'), ('PickelhaubeDark', DARK, 'dark')):
        out.write(f'\n/** Pickelhaube\'s own colours, {doc}: for Android before 12, which has no colours from the wallpaper. */\n')
        out.write(f'internal val {name} = {doc}ColorScheme(\n')
        for k, v in roles.items():
            out.write(f'    {k} = Color({v}),\n')
        out.write(')\n')
print('wrote', os.path.normpath(OUT))
